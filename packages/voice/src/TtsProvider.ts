/**
 * 읽어 주기 Provider 추상화 (F16).
 *
 * <p>`SttProvider`와 같은 자리에 같은 모양으로 둔다 — 말을 <b>듣는</b> 쪽이 교체 가능한
 * 부품이면, <b>읽어 주는</b> 쪽도 그래야 한다. 상용 전환 시 국내 TTS 엔진으로 바꿀 때
 * 바뀌는 것은 구현체 파일 하나다.
 *
 *   개발·데모   브라우저 speechSynthesis      비용 0, 번들 0KB
 *   상용 전환   상용 TTS API (국내 벤더)       유료, 목소리 품질이 낫다
 *
 * <p><b>왜 필요한가.</b> 큰 글씨는 저시력의 일부만 푼다. 확대해도 안 보이는 사람과,
 * 글을 빨리 읽기 어려운 사람에게는 화면을 키우는 것이 답이 아니다. 그리고 보내기 직전의
 * 확인 문구는 <b>가장 정확하게 전달돼야 하는 문장</b>인데 지금은 읽는 것 말고 길이 없다.
 *
 * <p><b>여기서 지키는 것 하나.</b> 계좌번호를 통째로 읽지 않는다(`maskDigits`).
 * 화면은 혼자 보지만 소리는 옆 사람도 듣는다 — 은행 창구 앞에서 계좌번호가 울려 퍼지는
 * 것은 접근성이 아니다. 전체를 듣고 싶은 사용자는 켤 수 있다.
 */

export interface TtsProvider {
  /** 이 환경에서 쓸 수 있는가. false면 호스트는 읽기 버튼을 아예 그리지 않는다. */
  readonly isSupported: boolean;

  /** 읽는다. 이미 읽는 중이면 그것을 멈추고 새로 읽는다. */
  speak(text: string): void;

  /** 멈춘다. 화면을 떠날 때 호스트가 부른다. */
  cancel(): void;
}

/**
 * 이어진 숫자를 뒤 네 자리만 남긴다.
 *
 * <p>순수 함수라 브라우저 없이 잰다. `guard.ts`가 네트워크 없는 판단을 밖으로 뺀 것과
 * 같은 규율이다.
 *
 * <p><b>금액은 건드리지 않는다.</b> 네 자리 이하이거나 콤마가 든 표기(`187,000원`)는
 * 그대로 둔다 — 확인 문구에서 금액이 가려지면 이 기능의 목적 자체가 사라진다.
 * 가리는 것은 <b>다섯 자리 이상 붙어 있는 숫자</b>, 즉 계좌번호와 전화번호 모양이다.
 */
export function maskDigits(text: string): string {
  return text.replace(/\d[\d-]{4,}/g, (match) => {
    const digits = match.replace(/\D/g, "");
    if (digits.length < 5) return match;
    return `끝 네 자리 ${digits.slice(-4)}`;
  });
}
