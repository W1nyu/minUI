import type { MenuId } from "../types.js";

/**
 * 어느 단계가 이 후보를 올렸는가. 왜 이게 나왔는지 설명하고 벤치마크를 분석할 때 쓴다.
 *
 * <p>`SearchPipeline`에서 떼어 낸 이유는 M11의 `neural.ts`가 같은 어휘를 써야 하기
 * 때문이다. 두 벌로 두면 한쪽만 고쳐진다 — 단계 강도는 <b>한 곳에만</b> 있어야 한다.
 */
export type MatchStage = "exact" | "learned" | "synonym" | "semantic" | "phonetic" | "neural";

export interface SearchCandidate {
  menuId: MenuId;
  score: number;
  matchedBy: MatchStage;
  /** 후보를 올린 표현. 사용자에게 "이거 말씀하신 건가요"를 보여줄 근거. */
  matchedTerm: string;
}

/**
 * 같은 점수라면 어느 단계를 근거로 볼 것인가. 클수록 강하다.
 *
 * <p>"사용자가 말한 그대로"가 가장 강한 근거이고, 통계적 유사도가 가장 약하다.
 * 이 순서는 기획안 §8.3의 단계 순서와 같다.
 *
 * <p>`learned`(M7)가 `exact` 바로 아래에 있는 이유: 이 기기의 사용자가 그 말을 하고 그
 * 메뉴로 갔다는 <b>관찰</b>은 카탈로그를 쓴 사람의 짐작보다 그 사람에게 잘 맞는다.
 * 그렇다고 이름을 정확히 부른 것을 이길 수는 없다 — 한때 잘못 배운 표현 하나가
 * 이름으로 부르는 사람을 계속 엉뚱한 곳으로 보내게 된다.
 *
 * <p><b>`neural`(M11)이 `synonym` 아래인 이유는 실측이다.</b> §16이 기록한 대로 사람이
 * 쓴 동의어는 80%, 모델이 만든 것은 27%였다. 원격 모델은 n-gram보다 강한 근거지만
 * <b>사람이 그 메뉴를 실제로 뭐라 부르는지</b>를 아는 사전을 이기지는 못한다.
 * 같은 점수라면 사람 쪽이 더 나은 내기다. 이 순서 자체가 가설이고,
 * `pnpm --filter tools tune:neural`이 뒤집어 보고 답한다.
 */
export const STAGE_STRENGTH: Record<MatchStage, number> = {
  exact: 5,
  learned: 4,
  synonym: 3,
  phonetic: 2,
  neural: 1,
  semantic: 0,
};

/**
 * 정확 매칭이 있으면 뒤 단계의 후보를 볼 필요가 없다.
 *
 * <p><b>학습(M7)은 여기 넣지 않는다 — 한 번 넣었다가 되돌렸다.</b> 넣으면 학습이 걸린
 * 순간 나머지 후보가 전부 사라지는데, 사용자가 후보를 훑다 엉뚱한 것을 한 번 누른 경우
 * <b>정답이 후보 목록에서 통째로 없어진다.</b> 실측에서 정답이 후보 안에 있던 4건이
 * 0건이 됐고, 되묻던 질의는 "오답 하나를 확신 있게 내미는" 상태가 됐다.
 *
 * <p>그것은 임계값을 0.30 대신 0.40으로 고른 이유(잘못된 확신)와 같은 실패다. 게다가
 * 후보가 하나뿐이면 사용자는 누르지 않고 창을 닫으므로 <b>올바른 학습이 일어날 기회조차
 * 없다</b> — 잘못 배운 말이 망각 기한까지 그대로 남는다. 후보를 남겨 두면 사용자가 옳은
 * 것을 눌러 스스로 바로잡는다(F4). 학습은 순위를 올릴 뿐 다른 후보를 지우지 않는다.
 *
 * <p><b>`neural`(M11)도 여기 넣지 않는다.</b> 같은 이유이고, 하나가 더 있다 — 원격 모델은
 * 끄거나 죽을 수 있다. 그것이 후보를 지우는 힘을 가지면 <b>모델이 있고 없고에 따라 후보
 * 목록이 달라진다.</b> 없어도 100% 돈다는 규칙 9는 "돈다"가 아니라 "같게 돈다"여야 한다.
 */
export const DECISIVE: ReadonlySet<MatchStage> = new Set<MatchStage>(["exact"]);
