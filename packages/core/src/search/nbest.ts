/**
 * 인식 대안을 함께 보는 설정 (M21, 기획안 §9.2).
 *
 * <p>브라우저 Web Speech는 들은 것을 하나로 확정하지 않는다 — 순위가 매겨진 대안을
 * 여러 개 준다. 이 앱은 지금까지 `maxAlternatives = 1`로 1순위만 받고 나머지를 버렸다.
 * <b>버린 것 안에 정답이 있는 경우가 공짜로 얻을 수 있는 회수다.</b>
 *
 * <p>값이 코드가 아니라 설정에 있는 이유는 불변 규칙 3이다 — 다른 언어로 포팅할 때
 * 설정과 픽스처가 그대로 재사용되어야 한다.
 */
export interface NbestSettings {
  /**
   * 대안까지 볼 것인가.
   *
   * <p>기본은 `false`다. `neural`·`phonology`와 같은 처분으로, 사전 등록한 게이트를
   * `bench:voice`가 통과시키기 전에는 켜지 않는다.
   */
  enabled: boolean;
  /**
   * 몇 개까지 볼 것인가. 1이면 지금까지와 같다.
   *
   * <p>브라우저가 주는 것보다 크게 잡아도 해롭지 않다 — 없는 대안은 오지 않는다.
   */
  maxHypotheses: number;
  /**
   * 순위 한 칸당 곱하는 감점.
   *
   * <p>STT가 1순위로 올린 데는 이유가 있다. 뒤 순위가 <b>동점으로 밀어내지 못하게</b>
   * 하되, 정답이 2순위에 있을 때는 넘어올 수 있을 만큼만 눌러야 한다. 1.0이면
   * 순위를 무시하고, 0에 가까울수록 1순위만 본다.
   */
  decayPerRank: number;
}
