/**
 * 질의 정규화 ① (기획안 §8.3).
 *
 * 사용자는 "관리비를 이체해야 하는데"라고 말하고, 카탈로그에는 "계좌 이체"가 있다.
 * 조사와 어미를 떼어 내야 뒤 단계(동의어·n-gram·자모)가 같은 것을 보게 된다.
 *
 * 형태소 분석기를 쓰지 않는 이유: 사전과 모델이 딸려 오는데, 그 무게는 온디바이스
 * 번들 예산에서 임베딩 모델과 같은 이유로 감당하기 어렵다(기획안 §14). 대신
 * 금융 도메인에서 실제로 나오는 어미·조사만 규칙으로 처리하고, 남는 오차는
 * 뒤 단계의 유사도 매칭이 흡수한다.
 */

/**
 * 어절 전체 또는 꼬리로 붙는, 뜻을 지지 않는 말들. 긴 것부터 시도한다.
 * "해야 하는데"처럼 여러 어미가 겹친 형태를 한 번에 떼기 위해서다.
 */
const SUFFIXES = [
  // 어미 — 길이 순
  "해야하는데",
  "하고싶은데",
  "해주세요",
  "하고싶어",
  "해야해요",
  "해야돼요",
  "하는데요",
  "하려고요",
  "해야하지",
  "해야되",
  "해야돼",
  "해야지",
  "해야해",
  "하고싶",
  "하려고",
  "하는데",
  "했는데",
  "할건데",
  "해줄래",
  "주세요",
  "해줘요",
  "해야",
  "해줘",
  "할래",
  "할까",
  "해요",
  "했어",
  "해서",
  "한다",
  "려고",
  "야해",
  "야지",
  "어야",
  "아야",
  "네요",
  "세요",
  "줘요",
  "줘",
  "야",
  "해",
  "네",
  "요",
  "죠",
  "지",
  // 조사 — 두 글자 이상
  "에서",
  "으로",
  "한테",
  "에게",
  "까지",
  "부터",
  "이랑",
  "처럼",
  "보다",
  "마다",
  "밖에",
  "라도",
  // 조사 — 한 글자
  "로",
  "랑",
  "도",
  "만",
] as const;

/**
 * 핵심 격조사. 이것들만은 한 글자 어간까지 허용한다 — "돈을"의 "돈"을 살리기 위해서다.
 * 반대로 "도"(보조사)를 여기 넣으면 "한도"가 "한"이 되어 버린다.
 */
const CORE_PARTICLES = new Set(["을", "를", "이", "가", "은", "는", "에", "의", "와", "과"]);

/**
 * 뜻을 보태지 않는 군말. 어절 전체가 이것이면 통째로 버린다.
 *
 * 벤치마크에서 놓친 질의의 절반이 여기서 나왔다. "돈 좀 부쳐야 하는데"는 사전에 있는
 * "돈 부쳐"와 글자가 다 겹치는데, 가운데 낀 "좀" 하나 때문에 포함 판정이 깨졌다.
 * 사람은 이런 말을 항상 섞어 쓴다.
 */
const FILLERS = new Set([
  "좀",
  "그냥",
  "다시",
  "한번",
  "잠깐",
  "혹시",
  "진짜",
  "제발",
  "이제",
  "그",
  "저",
  "어",
  "음",
  "뭐",
  "네",
  "예",
]);

const ALL_SUFFIXES = [...SUFFIXES, ...CORE_PARTICLES].sort((a, b) => b.length - a.length);

/** 어절을 가르는 것들. 문장부호는 여기서 함께 사라진다. */
const SEPARATORS = /[\s,.!?;:~"'()[\]{}<>/\\|+\-_=*&^%$#@`]+/u;

export function normalize(input: string): string {
  return input
    .normalize("NFC")
    .toLowerCase()
    .split(SEPARATORS)
    .map(stripSuffix)
    .join("");
}

/**
 * 어절 하나에서 꼬리를 뗀다.
 *
 * 어간이 한 글자로 줄어드는 것은 원칙적으로 막는다. "한도"에서 보조사 "도"를 떼면
 * "한"이 남는데, 그러면 한도 변경 메뉴를 영영 찾지 못한다. 이런 오검출이
 * 조사 하나 남는 것보다 훨씬 비싸다.
 */
function stripSuffix(word: string): string {
  if (FILLERS.has(word)) return "";

  for (const suffix of ALL_SUFFIXES) {
    if (!word.endsWith(suffix)) continue;

    const stem = word.slice(0, word.length - suffix.length);

    // 어절이 통째로 어미인 경우("해줘", "하는데") — 뜻이 없으므로 버린다.
    if (stem.length === 0) return "";

    if (stem.length >= 2) return stem;
    if (CORE_PARTICLES.has(suffix) && word.length >= 2) return stem;

    // 이 꼬리는 뗄 수 없다. 더 짧은 꼬리를 계속 찾아본다.
  }

  return word;
}
