import type { RiskLevel } from "@minui/core";

/**
 * 라벨만 보고 위험도를 1차 판정한다. **빌더와 LLM 보강기가 같은 규칙을 써야 한다.**
 *
 * <p>이 판정은 기획안 §9.3의 안전 경계로 이어진다 — `high`는 음성·검색에서 자동 실행되지
 * 않는다. 그래서 놓치는 쪽(위험한데 low)이 반대(안전한데 high)보다 나쁘다.
 *
 * <p>다만 반대쪽도 공짜가 아니다. 실측에서 하나은행 40개 중 <b>65%가 high</b>로 나왔는데,
 * 그러면 음성이 "언제나 확인 한 번 더"가 되어 주 기능이 무너진다. 원인은 규칙이 거칠어서였다 —
 * `해지계좌 조회`는 <b>읽기만 하는 화면</b>인데 `해지`라는 글자 때문에 high가 됐다.
 */

/** 자금이 움직이거나 인증·한도를 건드리는 말. */
const MUTATING =
  /이체|송금|출금|입금|해지|취소|납부|가입|신규|발급|재발급|등록|변경|신청|설정|매수|매도|주문|청약|상환|환전|환매|약정|서명|예약|충전|양도|비밀번호|비번|인증|보안|한도|OTP|승인|동의|이관|전환|폐쇄|정정/;

/**
 * 이 말로 끝나면 읽는 화면이다.
 *
 * <p>한국어 금융 메뉴는 <b>마지막 명사가 그 화면이 하는 일</b>이다. `해지계좌 조회`는
 * 해지가 아니라 조회고, `이체내역`은 이체가 아니라 내역이다. 앞에 붙은 말은 대상일 뿐이다.
 * 실제로 행위를 하는 메뉴는 `해지 신청`·`이체하기`처럼 행위가 끝에 온다.
 */
const READ_ONLY_TAIL = /(조회|내역|현황|명세|명세서|안내|소개|가이드|목록|리스트|이란|란\?|정보)$/;

/**
 * 읽는 화면 중에서도 **내 데이터를 보여 주는** 것.
 *
 * <p>`안내`·`소개`·`가이드`·`이란`·`정보`로 끝나는 것은 설명문이다 — `해외주식 거래안내`는
 * 남이 봐도 그만이고, 그것까지 막으면 접근성 손해만 남는다. 반면 `조회`·`내역`·`현황`은
 * <b>그 사람의 것</b>을 띄운다.
 */
const DATA_TAIL = /(조회|내역|현황|명세|명세서|목록|리스트)$/;

/**
 * 읽는 화면인데 **남이 보면 안 되는 것**을 보여 준다.
 *
 * <p>돈·계좌·거래에 관한 것만 넣는다. 환율이나 영업점 안내까지 막으면 음성이 "언제나
 * 확인 한 번 더"가 되어 주 기능이 무너진다 — 하나은행 40개 중 65%가 high로 나왔던
 * 그 실패와 같은 모양이다. <b>놓치는 쪽보다 과하게 막는 쪽이 나은 규칙이지만,
 * 여기서는 반대쪽 대가가 접근성이라 좁게 잡는다.</b>
 */
const SENSITIVE_READ = /잔액|잔고|계좌|예금|적금|거래|입출금|출금|송금|이체|카드|대출|한도|금액|자산|보유|평가|수익|연금|보험|증권|투자/;

/**
 * @param haystack 경로와 라벨을 이어 붙인 것. 경로에 `이체`가 있어도 라벨이 `내역`이면
 *   읽는 화면이므로, 판정은 <b>라벨을 기준으로</b> 한다.
 */
export function guessRisk(label: string, path: readonly string[] = []): RiskLevel {
  const trimmed = label.trim();

  // 라벨이 읽기로 끝나면 읽는 화면이다. 경로가 무엇이든 상관없다.
  if (READ_ONLY_TAIL.test(trimmed)) {
    /*
     * **읽는 화면이라고 다 같지 않다** (M11).
     *
     * 이 규칙은 여기까지 "돈이 움직이는가"만 봤다. 그래서 잔액·거래내역처럼 읽기만 하는
     * 화면이 `low`가 되고, 확신이 높으면 확인 없이 열렸다 — 잠금 해제된 기기를 잠깐 쥔
     * 사람이 "잔액 얼마야"로 볼 수 있다. **돈은 안 나가지만 정보는 나간다.**
     *
     * 읽는 화면이라는 판정은 그대로 두고 **무엇을 보여 주는가**를 한 겹 더 본다.
     * `medium`은 자동 실행만 막고 후보 제시는 그대로다.
     */
    return DATA_TAIL.test(trimmed) && SENSITIVE_READ.test(trimmed) ? "medium" : "low";
  }

  if (MUTATING.test(trimmed)) return "high";

  // 라벨만으로는 알 수 없을 때만 경로를 본다. `이체 > 간편이체`의 `간편이체`처럼
  // 라벨에 행위가 안 드러나는 경우가 있다.
  return path.some((part) => MUTATING.test(part)) ? "high" : "low";
}
