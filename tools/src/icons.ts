/**
 * 라벨에서 아이콘을 고른다.
 *
 * <p>자동 수집한 카탈로그는 아이콘이 전부 기본값이라 카드가 다 똑같이 생긴다. 그러면
 * <b>"큰 카드라 한눈에 알아본다"는 주장이 무너진다</b> — 글자를 읽어야만 구별되는 카드는
 * 목록과 다를 바 없다. Studio에서 처음 확인한 문제다.
 *
 * <p>LLM에게 묻지 않는 이유는 이것이 규칙으로 충분하기 때문이다. 금융 메뉴의 이름은
 * 정해진 낱말을 쓰고, 그 낱말이 곧 갈래다. 재 보고 안 되면 그때 모델을 부르면 된다.
 *
 */

/*
 * 순서가 규칙의 절반이다. 위에서부터 먼저 걸리는 것을 쓴다.
 *
 * **상품 갈래를 행위보다 먼저 본다.** `대출계좌조회`는 잔액 화면이 아니라 대출 화면이고,
 * `예금조회/추가입금`은 입금 화면이 아니라 예금 화면이다. 이름을 붙인 사람이 앞에 둔 명사가
 * 그 화면이 다루는 것이고, 뒤에 붙은 말은 거기서 하는 일이다.
 *
 * 예외가 하나 있다 — `자동이체`는 맨 위다. `이체`에 먼저 걸리면 정기성이 사라진다.
 */
const RULES: [RegExp, string][] = [
  [/자동이체|자동납부|정기|반복/, "repeat"],

  // 상품 갈래
  [/환율|외화|환전|해외|글로벌|달러/, "globe"],
  [/예금|적금|저축|신탁|목돈/, "savings"],
  [/대출|융자|담보|상환|빌리/, "bank"],
  [/펀드|주식|투자|수익률|채권|ETF|ELS|청약|매매/, "chart"],
  [/연금|퇴직|IRP|노후/, "coin"],
  [/카드/, "card"],
  [/인증|비밀번호|보안|OTP|잠금|본인확인/, "lock"],
  [/공과금|지로|세금|납부|고지서|보험료|관리비/, "doc"],

  // 하는 일
  [/이체|송금|보내기|출금|입금/, "transfer"],
  [/잔액|잔고|계좌조회|전체계좌|예수금|보유/, "wallet"],
  [/내역|명세|기록|이력|결과조회/, "list"],
  [/한도|제한|금액설정/, "gauge"],
  [/알림|통지|신고|분실/, "bell"],
  [/고객|상담|문의|지점|영업점|센터/, "person"],
  [/증명서|확인서|서류|발급/, "doc"],
];

/** 규칙에 안 걸리면 기본값. 호출자가 정한다. */
export function guessIcon(label: string, path: readonly string[] = [], fallback = "doc"): string {
  for (const [pattern, icon] of RULES) {
    if (pattern.test(label)) return icon;
  }
  // 라벨로 못 정하면 경로를 본다. `이체 > 자주쓰는계좌관리`처럼 라벨에 갈래가 안 드러나는 경우.
  for (const [pattern, icon] of RULES) {
    if (path.some((part) => pattern.test(part))) return icon;
  }
  return fallback;
}
